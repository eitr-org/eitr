#!/usr/bin/env python3
"""Project the single Store registry into QML; --check detects stale output."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'distro/lib'))
from eitr_store_kinds import load


def projection():
    rows = load(ROOT / 'distro/store-kinds.json')
    return '.pragma library\n\n// Generated by tools/store-kinds.py.\nvar kinds = ' + json.dumps(rows, ensure_ascii=False, indent=4) + ';\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'quickshell/desktop-bar/StoreKinds.js'
    content = projection()
    if args.check:
        if not target.exists() or target.read_text() != content:
            sys.exit('Store kind projection is stale')
    else:
        target.write_text(content)
