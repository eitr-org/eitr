#!/usr/bin/env python3
"""Build Elephant cloud menus and matching Walker layouts from their route definitions."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROVIDERS = {
    'aws': 'AWS', 'cloudflare': 'Cloudflare', 'azure': 'Azure', 'gcp': 'Google Cloud',
    'digitalocean': 'DigitalOcean', 'hetzner': 'Hetzner Cloud', 'oracle': 'Oracle Cloud',
    'vercel': 'Vercel', 'netlify': 'Netlify', 'ibm': 'IBM Cloud',
}
TEMPLATE = '''local paths = dofile((os.getenv("EITR_LIBRARY_ROOT") or "/usr/share/eitr/lib") .. "/paths.lua")
local i18n = dofile(paths.code("elephant/i18n.lua"))
Name = %s
NamePretty = i18n.tr(%s)
Parent = %s
Icon = %s
FixedOrder = true
GetEntries = dofile(paths.code("elephant/cloud-navigation-entries.lua"))(Name)
dofile(paths.code("walker/scripts/menus/alphabetical.lua"))
'''


def outputs():
    menus = json.loads((ROOT / 'walker/scripts/menus/cloud/navigation-menus.json').read_text())
    layout = (ROOT / 'walker/themes/current/item_menus-main.xml').read_text()
    result = {}
    for name, spec in menus.items():
        title = spec.get('title', PROVIDERS[spec['provider']])
        if spec.get('selector') and spec.get('action'):
            title = spec['action'].split('  ')[-1]
        text = TEMPLATE % tuple(json.dumps(value, ensure_ascii=False)
                                for value in (name, title, spec['parent'], spec.get('icon', '󰅟')))
        result[ROOT / 'elephant/menus' / (name + '.lua')] = text
        result[ROOT / 'walker/themes/current' / ('item_menus-' + name + '.xml')] = layout
    lines = ['# Cloud menu parents', '',
             'Generated by `python3 tools/cloud-menus-build.py` from',
             '`walker/scripts/menus/cloud/navigation-menus.json`.', '',
             'Selection: `~/.config/eitr/cloud-navigation.json` (private, mode 0600).',
             'Native contexts/scopes/regions for the seven private-workspace providers',
             'remain in `~/.config/eitr/cloud-accounts/<provider>/<name>/selection.json`.', '',
             'Every chain continues with `cloud -> development`.', '']
    for provider, title in PROVIDERS.items():
        lines += ['## ' + title, '', '```text']
        account_list = 'aws-profiles' if provider == 'aws' else provider + '-contexts'
        lines.append(account_list + ' -> cloud')
        lines += [name + ' -> ' + spec['parent'] for name, spec in sorted(menus.items())
                  if spec['provider'] == provider]
        lines += ['```', '']
    result[ROOT / 'docs/CLOUD-MENUS.md'] = '\n'.join(lines)
    return result


def build(check=False):
    stale = []
    for path, content in outputs().items():
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    return stale


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    arguments = parser.parse_args()
    failures = build(arguments.check)
    for filename in failures:
        print('Stale cloud menu output: ' + filename)
    raise SystemExit(bool(failures))
