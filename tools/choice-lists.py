#!/usr/bin/env python3
"""Generate fixed choice projections and modules; --check also verifies docs and shipped designs.

Workspace styles and lockscreen designs are projected into the files that list them.
Bar layouts, bar appearances and update channels are generated as one module per
language (ChoiceLists.js, eitr_choice_lists.py, choice-lists.lua) that consumers read.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'tools/choice-lists.json'
# Ordered groups: their order is the menu and double-click cycle order.
ORDERED = {
    'workspace_modes': {'id', 'label', 'description'},
    'window_layouts': {'id', 'label', 'description'},
    'scrolling_directions': {'id', 'label', 'description'},
    'scrolling_widths': {'id', 'label', 'description', 'value'},
    'scrolling_focus_fit': {'id', 'label', 'description', 'value'},
    'about_logos': {'id', 'label'},
    'window_gaps': {'id', 'label', 'description', 'inner', 'outer'},
    'bar_layouts': {'id', 'label', 'icon', 'description'},
    'bar_appearances': {'id', 'label', 'icon', 'description'},
    'update_channels': {'id', 'label', 'description', 'repository', 'database'},
}
# edgeStyle: the bar-settings key holding a layout's edge style (Island style or Side style).
OPTIONAL = {'keywords', 'edgeStyle'}
GENERATED_NOTICE = 'Generated by tools/choice-lists.py from tools/choice-lists.json; edit those, not this file.'


def translated_languages():
    """Every Eitr language except the English source (i18n/languages.json)."""
    return set(json.loads((ROOT / 'i18n/languages.json').read_text())['languages']) - {'en'}


def load_catalog(path=CATALOG):
    catalog = json.loads(path.read_text())
    for group in ('workspace_styles', 'lockscreen_designs'):
        rows = catalog[group]
        fields = {'id', 'label', 'handbook_labels'} if group == 'workspace_styles' else {'id', 'label'}
        if not rows or any(set(row) != fields or
                           any(not isinstance(row[key], str) or not row[key] for key in ('id', 'label'))
                           for row in rows):
            raise ValueError(f'Invalid {group} rows')
        if group == 'workspace_styles':
            for row in rows:
                translations = row['handbook_labels']
                if (not isinstance(translations, dict) or set(translations) != translated_languages() or
                        any(not isinstance(label, str) or not label for label in translations.values())):
                    raise ValueError('Invalid workspace Handbook labels')
        if len({row['id'] for row in rows}) != len(rows):
            raise ValueError(f'Duplicate {group} ids')
        if rows != sorted(rows, key=lambda row: row['label'].casefold()):
            raise ValueError(f'{group} must be alphabetical by label')
    for group, fields in ORDERED.items():
        rows = catalog[group]
        if (not rows or any(not fields <= set(row) <= fields | OPTIONAL for row in rows)
                or any(not isinstance(row[key], str) or not row[key] for row in rows for key in fields)
                or any(not re.fullmatch(r'[a-z][a-z0-9-]*', row['id']) for row in rows)
                or any('icon' in row and not re.fullmatch(r'[0-9A-F]{4,6}', row['icon']) for row in rows)
                or any('keywords' in row and (not isinstance(row['keywords'], list) or not all(isinstance(word, str) and word for word in row['keywords']))
                       for row in rows)):
            raise ValueError(f'Invalid {group} rows')
        if len({row['id'] for row in rows}) != len(rows):
            raise ValueError(f'Duplicate {group} ids')
    return catalog


def glyph(row):
    return chr(int(row['icon'], 16)) if 'icon' in row else ''


def module_rows(catalog, group):
    """The rows a module exposes, with icons as real glyphs."""
    return [{**{key: value for key, value in row.items() if key != 'icon'}, **({'icon': glyph(row)} if 'icon' in row else {})}
            for row in catalog[group]]


def lua_string(text):
    # Elephant's Lua 5.1 has no \u{} escape: write non-ASCII bytes as decimal escapes.
    return '"' + ''.join(chr(byte) if 32 <= byte < 127 and chr(byte) not in '"\\' else '\\' + str(byte)
                         for byte in text.encode()) + '"'


def lua_value(value, indent='    '):
    if isinstance(value, str):
        return lua_string(value)
    if isinstance(value, list):
        return '{' + ', '.join(lua_value(item, indent) for item in value) + '}'
    return '{' + ', '.join(f'{key} = {lua_value(item, indent)}' for key, item in value.items()) + '}'


def modules(catalog):
    """Whole generated files for the ordered groups, keyed by repository path."""
    groups = {'workspaceModes': 'workspace_modes', 'aboutLogos': 'about_logos', 'windowLayouts': 'window_layouts', 'scrollingDirections': 'scrolling_directions', 'scrollingWidths': 'scrolling_widths', 'scrollingFocusFit': 'scrolling_focus_fit', 'workspaceStyles': 'workspace_styles', 'windowGaps': 'window_gaps', 'barLayouts': 'bar_layouts', 'barAppearances': 'bar_appearances', 'updateChannels': 'update_channels'}
    javascript = ['.pragma library', f'// {GENERATED_NOTICE}', '']
    for name, group in groups.items():
        # ASCII escapes keep editors from dropping the icon glyphs.
        javascript.append(f'var {name} = [\n' + ',\n'.join('    ' + json.dumps(row) for row in module_rows(catalog, group)) + '\n];')
    javascript += ['',
                   'function ids(choices) { return choices.map(function(choice) { return choice.id; }); }',
                   '// The choice after CURRENT, wrapping round: the double-click cycle.',
                   'function next(choices, current) {',
                   '    var index = ids(choices).indexOf(current);',
                   '    return choices[(index + 1) % choices.length].id;',
                   '}',
                   'function label(choices, id) {',
                   '    for (var index = 0; index < choices.length; index++) if (choices[index].id === id) return choices[index].label;',
                   '    return "";',
                   '}', '']
    python = [f'"""{GENERATED_NOTICE}"""', '']
    for name, group in groups.items():
        constant = re.sub(r'(?<!^)(?=[A-Z])', '_', name).upper()
        python.append(f'{constant} = (\n' + ''.join(f'    {row!r},\n' for row in module_rows(catalog, group)) + ')')
    python += ['', '',
               'def ids(choices):',
               '    return tuple(choice["id"] for choice in choices)',
               '', '',
               'def next_choice(choices, current):',
               '    """The choice after CURRENT, wrapping round: the double-click cycle."""',
               '    order = ids(choices)',
               '    return order[(order.index(current) + 1) % len(order)] if current in order else order[0]',
               '', '',
               'def label(choices, identifier):',
               '    return next((choice["label"] for choice in choices if choice["id"] == identifier), "")',
               '']
    lua = [f'-- {GENERATED_NOTICE}', 'return {']
    for name, group in groups.items():
        key = re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()
        lua.append(f'    {key} = {{')
        for row in module_rows(catalog, group):
            lua.append(f'        {lua_value(row)},')
        lua.append('    },')
    lua += ['}', '']
    return {
        'quickshell/desktop-bar/ChoiceLists.js': '\n'.join(javascript),
        'distro/lib/eitr_choice_lists.py': '\n'.join(python),
        'elephant/choice-lists.lua': '\n'.join(lua),
    }


def projections(catalog):
    styles = [row['id'] for row in catalog['workspace_styles']]
    names = {row['id']: row['label'] for row in catalog['lockscreen_designs']}
    bar = 'quickshell/desktop-bar/'
    yield bar + 'handbook-controls-preview.qml', r'model: \[[^\]\n]*\]', 'model: ' + json.dumps(styles)
    yield 'elephant/menus/workspace-style.lua', r'local choices = \{[^\n]*\}', 'local choices = {' + ', '.join(json.dumps(style) for style in styles) + '}'
    yield bar + 'scripts/workspace-style.py', r'^STYLES = [^\n]*$', 'STYLES = ' + repr(tuple(styles))
    yield bar + 'scripts/workspace-color.py', r'^if style not in [^\n]*:$', 'if style not in ' + repr(tuple(styles)) + ':'
    yield 'quickshell/lockscreen/scripts/settings.py', r'^NAMES = \{.*?^\}', 'NAMES = {\n' + ''.join(f'    {identifier!r}: {label!r},\n' for identifier, label in names.items()) + '}'
    gallery = '[\n' + ',\n'.join('        {id: ' + json.dumps(identifier) + ', title: Eitr.I18n.tr(' + json.dumps(label, ensure_ascii=False) + ')}' for identifier, label in names.items()) + '\n    ]'
    yield 'quickshell/lockscreen/design-gallery.qml', r'(?<=readonly property var designs: )\[.*?^    \]', gallery


def check_documentation(catalog, root=ROOT):
    errors = []
    labels = [row['label'].replace(' · ', ' ') for row in catalog['lockscreen_designs']]
    documents = [root / 'quickshell/lockscreen/README.md', *sorted((root / 'quickshell/desktop-bar/handbook/content').rglob('appearance.md'))]
    for path in documents:
        text = ' '.join(path.read_text().split())
        start = text.find(labels[0])
        end = text.find(labels[-1], start)
        enumeration = text[start:end + len(labels[-1])] if start >= 0 and end >= 0 else ''
        # Separators: English, German, French, Spanish, Portuguese, then Japanese and Chinese
        # (、 and 和) and Korean (및).
        pattern = r'(?:,?\s+(?:and|und|et|y|e|和|및)\s+|,\s*|、)'.join(re.escape(label) for label in labels)
        if not re.fullmatch(pattern, enumeration):
            errors.append(f'{path.relative_to(root)}: stale or unordered design enumeration')
        # English count mentions are checked wherever the full list is documented.
        for count in re.findall(r'\b(\w+) (?:shipped (?:EITR )?designs|designs\.)', text):
            words = dict(enumerate(('zero', 'one', 'two', 'three', 'four', 'five',
                                    'six', 'seven', 'eight', 'nine', 'ten', 'eleven',
                                    'twelve', 'thirteen', 'fourteen', 'fifteen',
                                    'sixteen', 'seventeen', 'eighteen', 'nineteen', 'twenty')))
            if count not in (str(len(labels)), words.get(len(labels))):
                errors.append(f'{path.relative_to(root)}: stale design count {count}')
    localized_counts = {
        'de': (r'Vergleiche die (\w+) Designs', {9: 'neun'}),
        'es': (r'Compara los (\w+) diseños', {9: 'nueve'}),
        'fr': (r'Comparez les (\w+) modèles', {9: 'neuf'}),
        'pt_BR': (r'Compare os (\w+) desenhos', {9: 'nove'}),
    }
    for locale, (pattern, words) in localized_counts.items():
        path = root / f'quickshell/desktop-bar/handbook/content/{locale}/appearance.md'
        counts = re.findall(pattern, path.read_text())
        if len(counts) != 1 or counts[0] not in (str(len(labels)), words.get(len(labels))):
            errors.append(f'{path.relative_to(root)}: stale or missing design count')
    for path in sorted((root / 'quickshell/desktop-bar/handbook/content').rglob('desktop-bar.md')):
        locale = path.parent.name
        choices = [row.get('handbook_labels', {}).get(locale, row['label'])
                   for row in catalog['workspace_styles']]
        # Chinese quotes each label: “A”、“B”或“C”; Japanese lists with 、, Korean says 또는.
        pattern = r'(?:,?\s+(?:or|oder|o|ou|또는)\s+|,\s*|、|”、“|”或“)'.join(re.escape(label) for label in choices)
        text = ' '.join(path.read_text().split())
        if not re.search(pattern, text):
            errors.append(f'{path.relative_to(root)}: stale workspace styles')
    text = (root / 'quickshell/desktop-bar/README.md').read_text()
    expected = ', '.join(row['label'] for row in catalog['workspace_styles'][:-1]) + ' or ' + catalog['workspace_styles'][-1]['label']
    if expected not in text:
        errors.append('desktop-bar/README.md: stale workspace styles')
    actual = {str(path.parent.relative_to(root / 'quickshell/lockscreen/themes')) for path in (root / 'quickshell/lockscreen/themes').rglob('Main.qml')}
    if actual != {row['id'] for row in catalog['lockscreen_designs']}:
        errors.append('Lockscreen catalog differs from shipped Main.qml designs')
    return errors


def synchronize(check=False):
    catalog = load_catalog()
    errors = []
    for relative, content in modules(catalog).items():
        path = ROOT / relative
        if not path.exists() or path.read_text() != content:
            if check:
                errors.append(f'{relative}: stale generated module; run python3 tools/choice-lists.py')
            else:
                path.write_text(content)
    for relative, pattern, replacement in projections(catalog):
        path = ROOT / relative
        original = path.read_text()
        updated, count = re.subn(pattern, lambda match: replacement, original, flags=re.MULTILINE | re.DOTALL)
        if count != 1:
            errors.append(f'{relative}: expected one choice projection, found {count}')
        elif updated != original:
            if check:
                errors.append(f'{relative}: stale choices; run python3 tools/choice-lists.py')
            else:
                path.write_text(updated)
    return errors + check_documentation(catalog)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    arguments = parser.parse_args()
    failures = synchronize(arguments.check)
    for failure in failures:
        print(failure)
    raise SystemExit(bool(failures))
