const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const model = {};
vm.createContext(model);
vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'AiSelectionModel.js'), 'utf8').replace(/^\.pragma library\s*/, ''), model);
const available = ['Claude', 'Codex', 'Grok'];
const plain = value => JSON.parse(JSON.stringify(value));
assert.deepEqual(plain(model.reconcile(available, undefined)), ['Claude']);
assert.deepEqual(plain(model.reconcile(available, ['Grok', 'missing', 'Claude', 'Claude'])), ['Claude', 'Grok']);
assert.deepEqual(plain(model.reconcile([], ['Claude'])), []);
assert.deepEqual(plain(model.reconcile(['Codex'], ['Claude'])), ['Codex']);
assert.deepEqual(plain(model.toggle(available, ['Claude'], 'Claude')), ['Claude']);
assert.deepEqual(plain(model.toggle(available, ['Claude'], 'Codex')), ['Claude', 'Codex']);
assert.deepEqual(plain(model.toggle(available, ['Claude', 'Codex'], 'Claude')), ['Codex']);
assert.deepEqual(plain(model.toggle(available, ['Codex'], 'missing')), ['Codex']);
assert.deepEqual(plain(model.reconcile(available, JSON.parse(JSON.stringify(['Codex', 'Grok'])))), ['Codex', 'Grok']);
console.log('AI provider selection checks passed');
