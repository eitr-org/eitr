#!/usr/bin/env python3
"""Write each theme's app integration files from Eitr's own sources.

  themes/build-theme-files.py           rewrite them
  themes/build-theme-files.py --check   fail if any differs from what would be written

integrations.json names each theme's icon theme, VS Code theme and Neovim
colorscheme plugins; colors.toml is the theme's palette. From them this writes
icons.theme, vscode.json, neovim.lua (palette-driven plugins get their colors
from colors.toml) and btop.theme (always from colors.toml).
"""
import argparse
import json
from pathlib import Path
import sys
import tomllib

THEMES = Path(__file__).resolve().parent
HEADER = "-- Generated by themes/build-theme-files.py from integrations.json and colors.toml.\n"

# Neovim color names filled from the palette for plugins marked "palette", each with
# the colors.toml keys tried in order.
NEOVIM_PALETTE = {
    "bg": ["background"], "dark_bg": ["dark_background"], "darker_bg": ["darker_background"],
    "lighter_bg": ["lighter_background"], "fg": ["foreground"], "dark_fg": ["dark_foreground"],
    "light_fg": ["light_foreground"], "bright_fg": ["bright_foreground"], "muted": ["muted"],
    "red": ["red"], "yellow": ["yellow"], "orange": ["orange", "yellow"], "green": ["green"],
    "cyan": ["cyan"], "blue": ["blue"], "magenta": ["magenta"], "brown": ["brown", "dark_foreground"],
    "bright_red": ["bright_red", "red"], "bright_yellow": ["bright_yellow", "yellow"],
    "bright_green": ["bright_green", "green"], "bright_cyan": ["bright_cyan", "cyan"],
    "bright_blue": ["bright_blue", "blue"], "bright_magenta": ["bright_magenta", "magenta"],
    "accent": ["accent"], "cursor": ["cursor", "foreground"], "foreground": ["foreground"],
    "background": ["background"], "selection": ["selection"],
    "selection_foreground": ["selection_foreground", "foreground"],
    "selection_background": ["selection_background", "selection"],
}

# btop's theme keys, each with the colors.toml keys tried in order.
BTOP = [
    ("Window and text", [("main_bg", ["background"]), ("main_fg", ["foreground"]),
                         ("title", ["bright_foreground", "foreground"]), ("hi_fg", ["accent"]),
                         ("inactive_fg", ["muted"]), ("graph_text", ["light_foreground", "foreground"])]),
    ("Selected process", [("selected_bg", ["selection_background", "selection"]),
                          ("selected_fg", ["selection_foreground", "foreground"]), ("proc_misc", ["accent"])]),
    ("Box outlines and dividers", [("cpu_box", ["muted"]), ("mem_box", ["muted"]), ("net_box", ["muted"]),
                                   ("proc_box", ["muted"]), ("div_line", ["muted"]),
                                   ("meter_bg", ["dark_background", "selection"])]),
    ("CPU and temperature graphs, low to high", [
        ("cpu_start", ["green"]), ("cpu_mid", ["yellow"]), ("cpu_end", ["red"]),
        ("temp_start", ["blue"]), ("temp_mid", ["magenta"]), ("temp_end", ["red"])]),
    ("Memory meters", [
        ("free_start", ["cyan"]), ("free_mid", ["cyan"]), ("free_end", ["bright_cyan", "cyan"]),
        ("cached_start", ["blue"]), ("cached_mid", ["blue"]), ("cached_end", ["bright_blue", "blue"]),
        ("available_start", ["green"]), ("available_mid", ["green"]), ("available_end", ["bright_green", "green"]),
        ("used_start", ["yellow"]), ("used_mid", ["red"]), ("used_end", ["bright_red", "red"])]),
    ("Network graphs", [
        ("download_start", ["green"]), ("download_mid", ["cyan"]), ("download_end", ["bright_green", "green"]),
        ("upload_start", ["magenta"]), ("upload_mid", ["blue"]), ("upload_end", ["bright_magenta", "magenta"])]),
    ("Process list gradient", [("process_start", ["accent"]), ("process_mid", ["magenta"]),
                               ("process_end", ["red"])]),
]


# Every palette has the 16 terminal colors; named colors a palette leaves out use them.
TERMINAL = {"red": "color1", "green": "color2", "yellow": "color3", "blue": "color4", "magenta": "color5",
            "cyan": "color6", "bright_red": "color9", "bright_green": "color10", "bright_yellow": "color11",
            "bright_blue": "color12", "bright_magenta": "color13", "bright_cyan": "color14", "muted": "color8",
            "selection": "selection_background", "dark_background": "color0", "light_foreground": "color7",
            "bright_foreground": "color15"}


def color(palette, keys, theme):
    for key in keys + [TERMINAL[key] for key in keys if key in TERMINAL]:
        if isinstance(palette.get(key), str) and palette[key].startswith("#"):
            return palette[key]
    raise ValueError(f"{theme}/colors.toml has none of {', '.join(keys)}")


def lua(value, depth=1):
    indent = "\t" * depth
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    lines = []
    if "repo" in value:
        lines.append(indent + lua(value["repo"]) + ",")
    for key in sorted(name for name in value if name not in ("repo", "palette")):
        lines.append(f"{indent}{key} = {lua(value[key], depth + 1)},")
    return "{\n" + "\n".join(lines) + "\n" + "\t" * (depth - 1) + "}"


def neovim(theme, integration, palette):
    plugins = []
    for plugin in integration["plugins"]:
        plugin = json.loads(json.dumps(plugin))
        if plugin.get("palette"):
            colors = {name: color(palette, keys, theme) for name, keys in NEOVIM_PALETTE.items()}
            plugin.setdefault("opts", {})["colors"] = colors
        plugins.append(plugin)
    plugins.append({"repo": "LazyVim/LazyVim", "opts": {"colorscheme": integration["colorscheme"]}})
    return HEADER + "return {\n" + "\n".join("\t" + lua(plugin, 2) + "," for plugin in plugins) + "\n}\n"


def btop(theme, palette):
    lines = [f"# {theme}: generated by themes/build-theme-files.py from colors.toml.", ""]
    for section, keys in BTOP:
        lines.append(f"# {section}")
        lines += [f'theme[{name}]="{color(palette, sources, theme)}"' for name, sources in keys]
        lines.append("")
    return "\n".join(lines)


def files_for(theme, integration):
    palette = tomllib.loads((THEMES / theme / "colors.toml").read_text())
    vscode = {key: value for key, value in integration["vscode"].items()}
    return {
        "icons.theme": integration["icons"] + "\n",
        "vscode.json": json.dumps(vscode, indent=2, ensure_ascii=False) + "\n",
        "neovim.lua": neovim(theme, integration["neovim"], palette),
        "btop.theme": btop(theme, palette),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    integrations = json.loads((THEMES / "integrations.json").read_text())
    themes = sorted(path.name for path in THEMES.iterdir() if (path / "colors.toml").is_file())
    if sorted(integrations) != themes:
        raise SystemExit(f"integrations.json must list exactly these themes: {', '.join(themes)}")
    stale = []
    for theme in themes:
        for name, text in files_for(theme, integrations[theme]).items():
            path = THEMES / theme / name
            if arguments.check:
                if not path.is_file() or path.read_text() != text:
                    stale.append(str(path.relative_to(THEMES.parent)))
            else:
                path.write_text(text)
    if stale:
        print("Out of date; run themes/build-theme-files.py:\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
