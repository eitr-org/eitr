#!/usr/bin/env python3
"""Choose the user's terminal; Eitr utility terminals remain on Kitty."""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import signal

for parent in Path(__file__).resolve().parents:
    library = parent / 'lib'
    if not (library / 'eitr_paths.py').is_file():
        library = parent / 'distro/lib'
    if (library / 'eitr_paths.py').is_file():
        sys.path.insert(0, str(library))
        break
from eitr_paths import code, config, read_settings, write_settings
from eitr_i18n import tr


PREFERENCE = config('eitr/terminal.json')


def current():
    value = read_settings(PREFERENCE, {'terminal': 'kitty'})['terminal']
    if value not in ('kitty', 'ghostty'):
        raise ValueError('Invalid terminal preference')
    return value


def selected():
    return 'ghostty' if current() == 'ghostty' and shutil.which('ghostty') else 'kitty'


def choose(value):
    current()
    if value == 'ghostty' and not shutil.which('ghostty'):
        subprocess.Popen([str(code('walker/bin/menu-path/kitty')), '--class', 'eitr-software',
                          '-e', 'python3', str(code('walker/scripts/actions/task-terminal.py')),
                          'python3', str(Path(__file__).resolve()), 'install'], start_new_session=True)
        return
    if value == 'ghostty':
        sync()
    write_settings(PREFERENCE, {'terminal': value})


def install():
    from eitr_terminal import read_key
    print(tr('Install Ghostty? Enter: install · Esc: cancel'), flush=True)
    while True:
        key = read_key()
        if key in ('\x1b', '\x03', '\x04', ''):
            return
        if key in ('\r', '\n'):
            break
    subprocess.run(['python3', str(code('walker/scripts/actions/install/software.py')),
                    'recipe', 'tools', 'ghostty'], check=True)
    if not shutil.which('ghostty'):
        raise ValueError('Ghostty installation did not provide ghostty')
    choose('ghostty')


def sync():
    theme = config('theme/current')
    if not (theme / 'colors.toml').is_file():
        return
    sys.path.insert(0, str(code('walker/scripts/themes')))
    from palette import load
    colors = load(theme)
    background, foreground = colors['background'], colors['foreground']
    palette = []
    for index in range(16):
        fallback = palette[index - 8] if index >= 8 else (background if index == 0 else foreground)
        palette.append(colors.get(f'color{index}', fallback))
    family = read_settings(config('eitr/font.json'), {'family': 'JetBrainsMono Nerd Font'})['family']
    if not isinstance(family, str) or any(character in family for character in '\r\n\0'):
        raise ValueError('Invalid terminal font')
    lines = ['# Generated by Eitr. Personal overrides: ghostty/local.conf',
             f'font-family = {family}', 'font-size = 10', 'command = /usr/bin/zsh',
             'background-opacity = 0.75', 'window-padding-x = 0', 'window-padding-y = 0',
             'window-decoration = none', 'gtk-single-instance = false',
             'shell-integration = zsh', 'shell-integration-features = no-cursor',
             'cursor-style = block', 'cursor-style-blink = true',
             f'background = {background}', f'foreground = {foreground}',
             f"cursor-color = {colors.get('cursor', foreground)}", f'cursor-text = {background}',
             f"selection-background = {colors.get('selection_background', palette[8])}",
             f"selection-foreground = {colors.get('selection_foreground', foreground)}"]
    lines += [f'palette = {index}={color}' for index, color in enumerate(palette)]
    lines += ['config-file = ?local.conf']
    output = config('ghostty/eitr.conf')
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode='w', dir=output.parent, delete=False) as temporary:
        temporary.write('\n'.join(lines) + '\n')
    try:
        os.replace(temporary.name, output)
    finally:
        Path(temporary.name).unlink(missing_ok=True)
    if os.environ.get('EITR_NO_SESSION') != '1':
        # Only signal processes with a registered handler, including older releases.
        for process in Path('/proc').glob('[0-9]*'):
            try:
                if process.stat().st_uid != os.getuid() or (process / 'comm').read_text().strip() != 'ghostty':
                    continue
                status = dict(line.split(':', 1) for line in (process / 'status').read_text().splitlines() if ':' in line)
                if int(status['SigCgt'].strip(), 16) & (1 << (signal.SIGUSR2 - 1)):
                    os.kill(int(process.name), signal.SIGUSR2)
            except (OSError, ValueError, KeyError):
                continue


def launch(arguments):
    terminal = selected()
    if terminal == 'kitty':
        return ['kitty', *arguments]
    sync()
    translated = ['ghostty', '--config-file=' + str(config('ghostty/eitr.conf'))]
    while arguments:
        argument, *arguments = arguments
        if argument == '--directory':
            directory, *arguments = arguments
            translated.append('--working-directory=' + directory)
        elif argument.startswith('--directory='):
            translated.append('--working-directory=' + argument.split('=', 1)[1])
        elif argument == '-e':
            translated += ['-e', *arguments]
            break
        elif not argument.startswith('-'):
            translated += ['-e', argument, *arguments]
            break
        else:
            raise ValueError('Unsupported user terminal option: ' + argument)
    return translated


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=('get', 'set', 'install', 'sync', 'launch', 'summary'))
    parser.add_argument('arguments', nargs=argparse.REMAINDER)
    args = parser.parse_args()
    try:
        if args.action == 'summary':
            print(json.dumps({"current": selected(), "available": True,
                              "choices": [{"value": value, "label": label, "available": bool(shutil.which(value))}
                                          for value, label in (("kitty", "Kitty"), ("ghostty", "Ghostty"))]}))
        elif args.action == 'get':
            print(selected())
        elif args.action == 'set':
            if args.arguments not in (['terminal', 'kitty'], ['terminal', 'ghostty']):
                parser.error('set terminal kitty|ghostty')
            choose(args.arguments[1])
        elif args.action == 'install':
            install()
        elif args.action == 'sync':
            sync()
        else:
            command = launch(args.arguments)
            os.execvp(command[0], command)
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
