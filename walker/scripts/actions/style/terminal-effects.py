#!/usr/bin/env python3
"""Manage the optional built-in Kitty cursor fire effect without touching themes."""
import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

for parent in Path(__file__).resolve().parents:
    library = parent / 'lib'
    if not (library / 'eitr_paths.py').is_file():
        library = parent / 'distro/lib'
    if (library / 'eitr_paths.py').is_file():
        sys.path.insert(0, str(library))
        break
from eitr_paths import config, read_settings, write_settings
from eitr_i18n import tr

PREFERENCE = config('eitr/terminal.json')
OUTPUT = config('kitty/cursor-fire.conf')
LOADER = config('kitty/kitty.conf')
INCLUDE = 'globinclude cursor-fire.conf'


def read():
    settings = read_settings(PREFERENCE, {'cursor_fire': False})
    if type(settings['cursor_fire']) is not bool:
        raise ValueError(tr('Cursor Fire preference must be true or false'))
    return settings


def atomic_write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix='.' + path.name + '-', dir=path.parent)
    try:
        with os.fdopen(descriptor, 'w') as output:
            output.write(text)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def check_support():
    if not shutil.which('slangc'):
        raise ValueError(tr("Cursor Fire needs shader-slang. Install Eitr's updated desktop dependencies first."))
    result = subprocess.run(['kitty', '--version'], check=True, capture_output=True, text=True, timeout=5)
    match = re.search(r'kitty (\d+)\.(\d+)\.(\d+)', result.stdout)
    if not match or tuple(map(int, match.groups())) < (0, 49, 0):
        raise ValueError(tr('Cursor Fire needs Kitty 0.49 or newer.'))
    pipeline = 'cursor-trail-blaze'
    # Validate Kitty's built-in pipeline before changing the running terminal.
    check = ('from kitty.shaders.slang import parse_pipeline, build_custom_shader_pipeline_glsl; '
             f'build_custom_shader_pipeline_glsl(parse_pipeline({pipeline!r}))')
    subprocess.run(['kitty', '+runpy', check], check=True, capture_output=True, text=True, timeout=60)
    return pipeline


def sync(enabled, pipeline=None):
    if not LOADER.is_file():
        raise ValueError(tr("Kitty configuration is missing; start Eitr's user configuration setup first."))
    loader = LOADER.read_text()
    if enabled:
        pipeline = pipeline or check_support()
        # Personal options remain intact. This opt-in include overrides only
        # shader selection and the movement threshold while the effect is enabled.
        text = ('# Generated by Eitr Terminal settings.\n'
                f'custom_shaders "{pipeline}"\n'
                'cursor_trail 1\ncursor_trail_start_threshold 1\n')
    else:
        text = '# Generated by Eitr Terminal settings. Cursor Fire is disabled.\n'
    atomic_write(OUTPUT, text)
    lines = loader.splitlines()
    if not any(line.strip() == INCLUDE for line in lines):
        atomic_write(LOADER, loader.rstrip() + '\n' + INCLUDE + '\n')


def set_enabled(enabled):
    read()  # Fail read-only for unsupported preference versions.
    pipeline = check_support() if enabled else None
    sync(enabled, pipeline)
    write_settings(PREFERENCE, {'cursor_fire': enabled})
    if os.environ.get('EITR_NO_SESSION') != '1':
        subprocess.run(['pkill', '-USR1', '-u', str(os.getuid()), '-x', 'kitty'],
                       check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=('get', 'set', 'sync', 'summary'))
    parser.add_argument('key', nargs='?', choices=('cursor-fire',))
    parser.add_argument('value', nargs='?', choices=('off', 'on'))
    args = parser.parse_args()
    try:
        if args.action == 'summary':
            print(json.dumps({"current": read()['cursor_fire'],
                              "available": bool(shutil.which('kitty') and shutil.which('slangc') and LOADER.is_file()),
                              "choices": [{"value": False, "label": "Off"}, {"value": True, "label": "On"}]}))
        elif args.action == 'get':
            print('on' if read()['cursor_fire'] else 'off')
        elif args.action == 'set':
            if args.key != 'cursor-fire' or args.value is None:
                parser.error('set requires cursor-fire on|off')
            set_enabled(args.value == 'on')
        else:
            sync(read()['cursor_fire'])
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        message = str(error)
        print(message, file=sys.stderr)
        if args.action == 'set' and os.environ.get('EITR_NO_SESSION') != '1' and shutil.which('notify-send'):
            subprocess.run(['notify-send', '-u', 'normal', tr('Terminal settings'), message], check=False)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
