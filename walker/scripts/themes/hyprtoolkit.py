#!/usr/bin/env python3
"""Style Hyprland's own dialogs (the screen-share picker and other hyprtoolkit apps) like
Eitr's Settings app: the theme's colours, the chosen font and the corner preference.

Writes ~/.config/hypr/hyprtoolkit.conf, which hyprtoolkit reads when each dialog starts. A
file the person wrote themselves (without the generated header) is left alone."""
from pathlib import Path
import importlib.util
import os
import subprocess
import sys
import tomllib

HEADER = '# Generated by Eitr from the current theme, font and corners; edits are replaced.\n'
CODE = Path(__file__).resolve().parents[3]
CONFIG = Path(os.environ.get('XDG_CONFIG_HOME') or Path.home() / '.config')
TARGET = CONFIG / 'hypr/hyprtoolkit.conf'
# The Settings app's text roles: headings 16 px, body 13 px, captions 11 px.
SIZES = {'h1_size': 16, 'h2_size': 14, 'h3_size': 13, 'font_size': 13, 'small_font_size': 11}


def colour(value):
    value = value.strip().lstrip('#')
    if len(value) != 6 or any(character not in '0123456789abcdefABCDEF' for character in value):
        raise ValueError(f'not a colour: {value}')
    return f'rgb({value.lower()})'


def helper(*arguments):
    result = subprocess.run(['python3', *arguments], capture_output=True, text=True, timeout=10, check=True)
    return result.stdout.strip()


def corners():
    """Window rounding for large surfaces and half of it for buttons and rows."""
    spec = importlib.util.spec_from_file_location('desktop_style', CODE / 'quickshell/desktop-bar/scripts/desktop-style.py')
    style = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(style)
    large = int(style.current_style()['windowRounding'])
    return large, large // 2


def render(colors, family, rounding):
    large, small = rounding
    lines = [
        f'background = {colour(colors["background"])}',
        f'base = {colour(colors["surface"])}',
        f'alternate_base = {colour(colors["raised"])}',
        f'text = {colour(colors["foreground"])}',
        f'bright_text = {colour(colors.get("bright_foreground", colors["foreground"]))}',
        f'link_text = {colour(colors["accent"])}',
        f'accent = {colour(colors["accent"])}',
        f'accent_secondary = {colour(colors.get("second", colors["accent"]))}',
        f'rounding_large = {large}',
        f'rounding_small = {small}',
        *(f'{key} = {value}' for key, value in SIZES.items()),
        f'font_family = {family}',
        f'font_family_monospace = {family}',
        'icon_theme = eitr-current',
    ]
    return HEADER + '\n'.join(lines) + '\n'


def main():
    palette = CONFIG / 'theme/current/colors.toml'
    if not palette.is_file():
        return 0
    if TARGET.exists() and not TARGET.read_text().startswith(HEADER):
        return 0
    with palette.open('rb') as source:
        colors = tomllib.load(source)
    family = helper(str(CODE / 'walker/scripts/actions/style/fonts.py'), 'css').strip('"')
    text = render(colors, family, corners())
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    if not TARGET.exists() or TARGET.read_text() != text:
        temporary = TARGET.with_name(TARGET.name + '.tmp')
        temporary.write_text(text)
        os.replace(temporary, TARGET)
    return 0


if __name__ == '__main__':
    sys.exit(main())
